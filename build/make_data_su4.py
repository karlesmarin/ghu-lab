#!/usr/bin/env python3
"""make_data_su4.py — the second group, as data.

  Copyright (c) 2026 Carles Marin. All rights reserved.
  Author: Carles Marin <karlesmarin@gmail.com>  (with Claude, Anthropic, as assistant)

  Emits data/su4_ahmn.json from the published tools' own catalogues.  Nothing is retyped.

This is the file that decides whether DESIGN.md D3 was true or merely stated.  The kernel claims to
know about weight lattices, parities and winding sums, and to treat a GROUP AS DATA.  Until now it
held exactly one group, so the claim cost nothing.  A second one either drops in without touching a
line of kernel, or the claim was decoration.

Source of truth: ghu-explorer/tools/su4_data.json (weight histograms per
representation, keyed by Dynkin labels) and calc_data.json (the catalogue with dimensions and the
blind flag).  Both are themselves generated by that repo's make_calc_data.py, which fails if a row
disagrees with Part IV's Proposition 1.
"""
import json
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
# the published repository's own July data, beside this one unless GHU_EXPLORER says otherwise
SRC = pathlib.Path(os.environ.get("GHU_EXPLORER",
                                  pathlib.Path(__file__).resolve().parent.parent.parent
                                  / "ghu-explorer")) / "tools"

for f in ("su4_data.json", "calc_data.json"):
    if not (SRC / f).exists():
        sys.exit(f"FATAL: {SRC / f} is not there.  This file must not invent a catalogue it "
                 f"cannot read.")

su4 = json.loads((SRC / "su4_data.json").read_text(encoding="utf-8"))
calc = json.loads((SRC / "calc_data.json").read_text(encoding="utf-8"))

# calc_data carries dim and the blind flag; su4_data carries the weight histogram.  BOTH are keyed
# by the Dynkin labels "a,b,c" -- the `m` field inside a row is something else entirely, and taking
# it for the labels would have silently mislabelled every representation.
by_labels = {}
for key, row in calc["reps"].items():
    a, b, c = (int(x) for x in key.split(","))
    by_labels[(a, b, c)] = row

reps_dynkin, reps_hist, reps_modes, reps_box, catalogue = {}, {}, {}, {}, []
for key, entry in su4["reps"].items():
    a, b, c = (int(x) for x in key.split(","))
    name = f"({a},{b},{c})"
    reps_dynkin[name] = [a, b, c]
    reps_hist[name] = entry["h"]
    row = by_labels.get((a, b, c), {})
    catalogue.append({
        "name": name, "dynkin": [a, b, c], "dim": entry.get("dim", row.get("dim")),
        "blind": row.get("blind"),
    })
    # The CALCULATOR's engine does not use the histogram at all: it uses `modes`, a list of
    # (q, A, B) with q taking HALF-INTEGER values.  That is where alpha_1's period 2 comes from,
    # and porting the histogram engine instead is what made the AHMN anchor miss.
    if row.get("modes") is not None:
        reps_modes[name] = row["modes"]
    # Part IV's box (p,q,r) and its parity index zeta.  The eta-meter's whole closed form is these
    # two, so they are data like everything else about a group.
    if row.get("sides") is not None:
        reps_box[name] = {"sides": row["sides"], "zeta": row.get("zeta"),
                          "blind": row.get("blind")}
catalogue.sort(key=lambda r: (r["dim"] if r["dim"] is not None else 1e9, r["name"]))

DATA = {
    "id": "su4_ahmn",
    "group": "SU(4)",
    "orbifold": {"name": "T2/Z2",
                 "note": "the 6D SU(4) gauge-Higgs unification of arXiv:2312.08608, whose weak "
                         "mixing angle comes out sin^2(theta_W) = 1/4 at the compactification scale"},
    "source": {
        "papers": "Parts III-V of the series; the model is AHMN, arXiv:2312.08608",
        "extracted_from": ["ghu-explorer/tools/su4_data.json", "ghu-explorer/tools/calc_data.json"],
        "chain": "both files are generated by ghu-explorer/tools/make_calc_data.py, which fails a "
                 "row that disagrees with Part IV's Proposition 1 or whose character no (p,q,r) "
                 "reproduces",
    },
    # Dynkin labels are what the selection rule of Part III is a statement ABOUT.  Their presence
    # here is the difference between a question that can be asked and one that cannot.
    "reps_dynkin": reps_dynkin,
    "reps_hist": reps_hist,
    "reps_modes": reps_modes,
    "reps_box": reps_box,
    "adjoint": calc.get("adjoint"),
    "catalogue": catalogue,
    # THE TWO FIELDS THAT USED TO BE HERE ARE GONE, and the reason is worth keeping.
    # `gauge` (a VEV-dependent adjoint histogram) and `wg = 0.35` came from the July tool, where
    # `higgs_mh.py` fitted the weight explicitly "so 35 min = AHMN (0.438, 0.299)".  This kernel
    # reads NEITHER: `spectrum()` builds the potential from `reps_modes` alone, and the gauge
    # sector enters as the adjoint row carrying role = -1.  Measured before removing them --
    # wg from 0.20 to 1.00 moves neither the vacuum nor the mass ratio by a digit.
    #
    # They mattered because they made an honest agreement look circular: a data file that
    # advertises a weight calibrated to the very number the page then claims to reproduce is a
    # file that has to be audited before the claim can be believed.  Dead data that documents a
    # calibration the engine does not apply is worse than no data.  [[circular-artifact-measurement-returns-definition]]
    "calibration_note": "none: this model's potential is built from reps_modes and the role = -1 "
                        "adjoint row. The July tool's fitted gauge weight (wg = 0.35, calibrated "
                        "to AHMN's own minimum) is NOT used by this kernel and is not carried.",
    # KMAX is the calculator's (calc_shell.html), not the selection tool's 5.  It was typed rather
    # than read once, and the AHMN ratio came out 0.1 % low because of it.
    "kmax": 10,
    "grid": 72,
    # THE ANCHOR, in one place.  It was typed into three sections by hand, which is three chances
    # for the published content to drift from itself.  The shell also seeds the model with it, so
    # the instrument opens on a computation instead of on five dashes.
    "anchor": {
        "label": "AHMN 2312.08608",
        "bulk": [
            {"rep": "(4,0,0)", "parities": [1, 1], "multiplicity": 3, "eta": 1, "role": 1},
            {"rep": "(1,0,1)", "parities": [1, 1], "multiplicity": 1, "eta": 1, "role": -1},
        ],
    },
    "note": su4.get("note"),
}

out = HERE / "data" / "su4_ahmn.json"
out.write_text(json.dumps(DATA, indent=1, ensure_ascii=False), encoding="utf-8")
print(f"wrote {out}  ({out.stat().st_size / 1024:.0f} kB)")
print(f"  {len(reps_dynkin)} representations, {len(reps_modes)} with calculator modes")
print(f"  adjoint = {calc.get('adjoint')}")
small = [r for r in catalogue if r["dim"] and r["dim"] <= 20][:6]
for r in small:
    print(f"    {r['name']:<10} dim {r['dim']:<4} blind={r['blind']}")
